import { expect, test } from '@playwright/test';
test.use({ trace: 'off' });
test('two sessions share lasers, shield damage, death, reconnect, respawn and reset', async ({ browser }) => {
  test.setTimeout(60000);
  const ca = await browser.newContext(); const cb = await browser.newContext();
  const a = await ca.newPage(); const b = await cb.newPage();
  try {
    await a.goto('/'); await b.goto('/');
    await a.getByLabel('Your callsign').fill('Cipher'); await a.getByRole('button', { name: 'Create Room', exact: true }).click();
    await expect(a.getByTestId('room-code')).toBeVisible();
    const code = (await a.getByTestId('room-code').textContent())!;
    await b.getByLabel('Your callsign').fill('Ghost'); await b.getByLabel('Room code', { exact: true }).fill(code);
    await b.getByRole('button', { name: 'Join Room', exact: true }).click();
    await expect(a.getByTestId('roster-member')).toHaveCount(2);
    await a.getByRole('button', { name: 'Ready up' }).click(); await b.getByRole('button', { name: 'Ready up' }).click();
    await expect(a.getByRole('button', { name: 'Start Match' })).toBeEnabled(); await a.getByRole('button', { name: 'Start Match' }).click();
    await expect(a.getByTestId('connection-status')).toHaveText('connected');
    await expect(b.getByTestId('connection-status')).toHaveText('connected');
    const local = b.locator('[data-self="true"]'); const id = (await local.getAttribute('data-player-id'))!;
    const remote = a.locator(`[data-player-id="${id}"]`);
    await expect(a.getByTestId('hazard-status')).toHaveAttribute('data-phase', 'warning', { timeout: 10000 });
    await a.getByRole('button', { name: /^Shield/ }).click();
    await expect(b.getByTestId('hazard-status')).toHaveAttribute('data-phase', 'active');
    await expect(local).toHaveAttribute('data-health', '50'); await expect(remote).toHaveAttribute('data-health', '50');
    await expect(a.locator('[data-self="true"]')).toHaveAttribute('data-health', '100');
    await expect(a.getByTestId('damage-notice')).toContainText('Shield blocked');
    await b.reload(); await expect(b.getByTestId('connection-status')).toHaveText('connected');
    await expect(local).toHaveAttribute('data-health', '50');
    await expect(b.getByTestId('hazard-status')).toHaveAttribute('data-phase', 'idle');
    await expect(local).toHaveAttribute('data-life', 'respawning', { timeout: 10000 });
    await expect(remote).toHaveAttribute('data-life', 'respawning');
    await expect(b.getByRole('button', { name: /^Dash/ })).toBeDisabled();
    const x = await local.getAttribute('data-x'); await b.keyboard.down('KeyD');
    await b.waitForTimeout(300); await b.keyboard.up('KeyD'); expect(await local.getAttribute('data-x')).toBe(x);
    await b.reload(); await expect(b.getByTestId('connection-status')).toHaveText('connected');
    await expect(local).toHaveAttribute('data-life', 'respawning');
    await expect(local).toHaveAttribute('data-life', 'alive'); await expect(local).toHaveAttribute('data-health', '100');
    await expect(b.locator('.health-hud [data-testid="health"]')).toHaveAttribute('data-invulnerable', 'true');
    await expect(remote).toHaveAttribute('data-health', '100');
    await b.screenshot({ path: 'test-results/phase3c-respawn.png', fullPage: true });
    await a.getByRole('button', { name: 'Return to Lobby' }).click();
    await expect(b.getByTestId('room-status')).toHaveText('LOBBY');
    await expect(b.getByTestId('ability-hud')).toHaveCount(0);
    await a.getByRole('button', { name: 'Ready up' }).click(); await b.getByRole('button', { name: 'Ready up' }).click();
    await expect(a.getByRole('button', { name: 'Start Match' })).toBeEnabled(); await a.getByRole('button', { name: 'Start Match' }).click();
    await expect(b.locator('[data-self="true"]')).toHaveAttribute('data-health', '100');
    await expect(b.getByTestId('hazard-status')).toHaveAttribute('data-phase', 'idle');
  } finally { await ca.close(); await cb.close(); }
});
